def is_anagram(s,t):
  if len(s) != len(t):
    return False

  count = [0] * 26

  for i in range(len(s)):
    count[ord(s[i])-ord('a')] += 1
    count[ord(s[i])-ord('a')] -= 1

  return all(c == 0 for c in count)

print(is_anagram(s,t))

