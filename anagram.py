def is_anagram(s,t):
  letter = {}
  if len(s) != len(t):
    return False

  for val in s:
    if val in letter:
        letter[val]+=1
    else:letter[val]=1

  for val in t:
    if val in letter:
      if letter[val] > 0:
         letter[val]-=1
      else: return False

    else: return False

  return True

s = "anagram"
t = "nagaram"
print(is_anagram(s,t))

