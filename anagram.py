def is_anagram(s, t):
    if len(s) != len(t):
        return False

    letter = {}

    for val in s:
        letter[val] = letter.get(val, 0) + 1

    for val in t:
        if letter.get(val, 0) == 0:
            return False
        letter[val] -= 1

    return True

print(is_anagram(s,t))

