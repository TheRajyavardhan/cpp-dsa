## More refined version

def longest_substr_with_k_distinct_char(s, k):
    if k == 0:
        return 0

    left = 0
    have = {}
    max_len = 0

    for right in range(len(s)):
        c = s[right]
        have[c] = have.get(c, 0) + 1

        # Shrink window if distinct chars > k
        while len(have) > k:
            left_char = s[left]
            have[left_char] -= 1
            if have[left_char] == 0:
                del have[left_char]
            left += 1

        # Update max length (VALID window)
        max_len = max(max_len, right - left + 1)

    return max_len