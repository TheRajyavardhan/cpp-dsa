def longest_substr_with_k_distinct_char(s,k):

  if not k:
    return 0

  left = 0
  required = k
  have = {}
  char = 0
  max_len = float('-inf')

  for right in range(len(s)):
    c = s[right]
    have[c] = have.get(c,0)+1

    if have[c] == 1: char+=1

    if char == required and right - left + 1 > max_len:
        max_len = right - left + 1

    while char > required:
      left_char = s[left]
      if have[left_char] == 1:
        char -= 1
      have[left_char] -= 1
      left+=1

  return max_len

